// --- Async access seam -------------------------------------------------------
// Pages read the catalogue through these, never by importing `products`
// directly, so the backing store can change without touching call sites.

export async function getProducts(): Promise<Product[]> {
  return products;
}

export async function getProductBySlug(slug: string): Promise<Product | undefined> {
  return products.find((p) => p.slug === slug);
}

export async function getBrands(category?: Category): Promise<string[]> {
  const pool = category ? products.filter((p) => p.category === category) : products;
  return [...new Set(pool.map((p) => p.brand))].sort((a, b) => a.localeCompare(b));
}

export async function getPriceBounds(): Promise<{ minMinor: number; maxMinor: number }> {
  const prices = products.map((p) => p.priceMinor);
  return { minMinor: Math.min(...prices), maxMinor: Math.max(...prices) };
}
